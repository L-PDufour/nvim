-- Picker keymaps (snacks.picker; setup lives in config.snacks).
local pick = require("snacks").picker

local nmap_leader = function(suffix, rhs, desc)
	vim.keymap.set("n", "<Leader>" .. suffix, rhs, { desc = desc })
end

nmap_leader("ff", function()
	pick.files()
end, "Files")
nmap_leader("fh", function()
	pick.help()
end, "Help tags")
nmap_leader(".", function()
	pick.resume()
end, "Resume")
nmap_leader("fq", function()
	pick.qflist()
end, "Quickfix")
nmap_leader("fQ", function()
	pick.loclist()
end, "Loclist")
nmap_leader("fd", function()
	pick.diagnostics_buffer()
end, "Diagnostic buf")
nmap_leader("fD", function()
	pick.diagnostics()
end, "Diagnostic workspace")
nmap_leader("fs", function()
	pick.lsp_workspace_symbols()
end, "Symbols workspace")
nmap_leader("fm", function()
	pick.marks()
end, "Marks")
nmap_leader("fr", function()
	pick.registers()
end, "Registers")
nmap_leader("<space>", function()
	pick.grep()
end, "Grep live")
nmap_leader("/", function()
	pick.lines()
end, "Lines")
nmap_leader("fw", function()
	pick.grep_word()
end, "Grep word")
nmap_leader("j/", function()
	pick.search_history()
end, '"/" history')
nmap_leader("j;", function()
	pick.command_history()
end, '":" history')
nmap_leader("k", function()
	pick.buffers()
end, "Buffers")

vim.api.nvim_create_autocmd("LspAttach", {
	callback = function(args)
		local function map_buf(lhs, rhs, desc)
			vim.keymap.set("n", lhs, rhs, { buffer = args.buf, desc = desc })
		end

		-- The lsp pickers use `auto_confirm`, so a single result jumps
		-- straight there instead of opening the picker.
		map_buf("grr", function()
			pick.lsp_references()
		end, "References")
		map_buf("gri", function()
			pick.lsp_implementations()
		end, "Implementations")
		map_buf("grt", function()
			pick.lsp_type_definitions()
		end, "Type definitions")
		map_buf("gra", vim.lsp.buf.code_action, "Code action")
		map_buf("gO", function()
			pick.lsp_symbols()
		end, "Document symbols")
		map_buf("gd", function()
			pick.lsp_definitions()
		end, "Definitions")
		map_buf("gD", function()
			pick.lsp_declarations()
		end, "Declarations")
	end,
})
